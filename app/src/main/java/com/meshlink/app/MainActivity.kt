    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()

        setContent {
            MeshLinkTheme {
                Surface(modifier = Modifier.fillMaxSize()) {
                    MeshLinkNavHost()
                }
            }
        }
    }
}
